#!/bin/sh
# Configure the FRAME156's Lontium LT8911EXB DSI-to-eDP bridge from a shell
# on the frame (busybox i2cset/i2cget, devmem), for bring-up before there's
# a kernel driver. A port of the register sequence in the 4.4-era vendor
# driver (github.com/aystshen/lontium_lt8911exb_driver).
#
# The DSI host must already be streaming video, and the timings here must
# be the ones the DSI host actually sends (the DRM mode), not the separate
# lontium,* values in the stock device tree: with those, the bridge locks
# onto the MIPI input but passes no video. Defaults are unit 1's
# working values (1920x1080 at 152.6 MHz, 2 eDP lanes, 8-bit), verified on
# 2026-10-17. Override from the environment for other panels.
# TEST=1 makes the bridge send its own test pattern instead of DSI video.

BUS=${BUS:-2}
ADDR=${ADDR:-0x29}
PCLK=${PCLK:-152600000}
HACT=${HACT:-1920}
VACT=${VACT:-1080}
HBP=${HBP:-140}
HFP=${HFP:-140}
HS=${HS:-40}
VBP=${VBP:-30}
VFP=${VFP:-20}
VS=${VS:-10}
MIPI_LANE=${MIPI_LANE:-4}
LANE_CNT=${LANE_CNT:-2}
COLOR=${COLOR:-1}
TEST=${TEST:-0}

w() { i2cset -y "$BUS" "$ADDR" "$1" "$2"; }
r() { i2cget -y "$BUS" "$ADDR" "$1"; }
hi() { printf '0x%02x' $(( $1 / 256 )); }
lo() { printf '0x%02x' $(( $1 % 256 )); }

# GPIO3 bank (PX30 GPIO v1: DR at 0x00, DDR at 0x04)
gpio3_set() { # pin value
	dr=$(devmem 0xff270000 32)
	if [ "$2" = 1 ]; then dr=$(( dr | (1 << $1) )); else dr=$(( dr & ~(1 << $1) )); fi
	devmem 0xff270000 32 $dr
	ddr=$(devmem 0xff270004 32)
	devmem 0xff270004 32 $(( ddr | (1 << $1) ))
}

PCLK10K=$(( PCLK / 10000 ))
HTOTAL=$(( HACT + HBP + HFP + HS ))
VTOTAL=$(( VACT + VBP + VFP + VS ))

# Panel standby (GPIO3_C4) off, then pulse the bridge reset (GPIO3_C5)
gpio3_set 20 1
usleep 20000
gpio3_set 21 0
usleep 150000
gpio3_set 21 1
usleep 150000

w 0xff 0x81
echo "chip id: $(r 0x00) $(r 0x01) $(r 0x02)"

# MIPI video timing
w 0xff 0xd0
w 0x0d "$(hi $VTOTAL)"; w 0x0e "$(lo $VTOTAL)"
w 0x0f "$(hi $VACT)";   w 0x10 "$(lo $VACT)"
w 0x11 "$(hi $HTOTAL)"; w 0x12 "$(lo $HTOTAL)"
w 0x13 "$(hi $HACT)";   w 0x14 "$(lo $HACT)"
w 0x15 "$(lo $VS)"
w 0x16 "$(lo $HS)"
w 0x17 "$(hi $VFP)";    w 0x18 "$(lo $VFP)"
w 0x19 "$(hi $HFP)";    w 0x1a "$(lo $HFP)"

# eDP video (MSA from registers)
w 0xff 0xa8
w 0x2d 0x88
w 0x05 "$(hi $HTOTAL)"; w 0x06 "$(lo $HTOTAL)"
w 0x07 "$(hi $((HS + HBP)))"; w 0x08 "$(lo $((HS + HBP)))"
w 0x09 "$(hi $HS)";     w 0x0a "$(lo $HS)"
w 0x0b "$(hi $HACT)";   w 0x0c "$(lo $HACT)"
w 0x0d "$(hi $VTOTAL)"; w 0x0e "$(lo $VTOTAL)"
w 0x11 "$(hi $((VS + VBP)))"; w 0x12 "$(lo $((VS + VBP)))"
w 0x14 "$(lo $VS)"
w 0x15 "$(hi $VACT)";   w 0x16 "$(lo $VACT)"

# Init
w 0xff 0x81; w 0x49 0xff
w 0xff 0x82; w 0x5a 0x0e
# MIPI Rx analog
w 0xff 0x82; w 0x32 0x51; w 0x35 0x42; w 0x4c 0x0c; w 0x4d 0x00
w 0x3a 0x44; w 0x3b 0x44
# Pixel clock recovery PLL
w 0xff 0x82; w 0x6a 0x40; w 0x6b 0x40
if [ $PCLK10K -lt 8800 ]; then w 0x6e 0x82; POSTDIV=8; else w 0x6e 0x81; POSTDIV=4; fi
PCR_M=$(( PCLK10K * POSTDIV / 25 / 100 ))
w 0xff 0x85
w 0xa9 0x31; w 0xaa 0x17; w 0xab 0xba; w 0xac 0xe1; w 0xad 0x47
w 0xae 0x01; w 0xae 0x11
# Digital top: MIPI Rx in, no dither
w 0xff 0x85; w 0xc0 0x01; w 0xb0 0x00
# MIPI Rx digital
w 0xff 0xd0
w 0x00 "$(printf '0x%02x' $(( MIPI_LANE % 4 )))"
w 0x02 0x08; w 0x08 0x00; w 0x0a 0x12; w 0x0c 0x40
w 0x1c 0x3a; w 0x31 0x0a
w 0x3f 0x10; w 0x40 0x20; w 0x41 0x30
if [ "$TEST" = 1 ]; then w 0x26 "$(printf '0x%02x' $(( PCR_M | 0x80 )))"; else w 0x26 "$(printf '0x%02x' $PCR_M)"; fi
w 0xff 0x81; w 0x03 0x7b; w 0x03 0xff
# Tx PLL 2.7 GHz
w 0xff 0x87; w 0x19 0x31
w 0xff 0x82; w 0x02 0x42; w 0x03 0x00; w 0x03 0x01
w 0xff 0x81; w 0x09 0xfc; w 0x09 0xfd
w 0xff 0x87; w 0x0c 0x11
locked=0
for i in 1 2 3 4 5; do
	usleep 5000
	if [ $(( $(r 0x37) & 0x02 )) -ne 0 ]; then locked=1; break; fi
	w 0xff 0x81; w 0x09 0xfc; w 0x09 0xfd
	w 0xff 0x87; w 0x0c 0x10; w 0x0c 0x11
done
echo "tx pll locked: $locked"
# Tx PHY
w 0xff 0x82
w 0x11 0x00; w 0x13 0x10; w 0x14 0x0c; w 0x14 0x08; w 0x13 0x20
w 0x0e 0x25; w 0x12 0xff
# eDP Tx digital
w 0xff 0xa8
if [ "$TEST" = 1 ]; then w 0x24 0x50; w 0x25 0x70; w 0x27 0x50; else w 0x27 0x10; fi
if [ "$COLOR" = 1 ]; then w 0x17 0x10; w 0x18 0x20; else w 0x17 0x00; w 0x18 0x00; fi
w 0xff 0xa0; w 0x00 0x08; w 0x01 0x00

# Video check (MIPI input)
w 0xff 0x85; w 0x1d 0x00; w 0x40 0xf7; w 0x41 0x30; w 0xa1 0x82
w 0xff 0x81; w 0x09 0x7d; w 0x09 0xfd
w 0xff 0x85
usleep 30000
if [ "$(r 0x50)" = 0x03 ]; then
	echo "mipi byte clk: $(( ($(r 0x4d) << 16) + ($(r 0x4e) << 8) + $(r 0x4f) )) kHz"
else
	echo "mipi byte clk: unstable"
fi
echo "vtotal: $(( ($(r 0x76) << 8) + $(r 0x77) ))"
w 0xff 0xd0
echo "hact: $(( ( ($(r 0x82) << 8) + $(r 0x83) ) / 3 ))  vact: $(( ($(r 0x85) << 8) + $(r 0x86) ))"

# Link training
dpcd_write() { # address data
	w 0xff 0xa6
	w 0x2b "$(printf '0x%02x' $(( 0x80 | (($1 >> 16) & 0x0f) )))"
	w 0x2b "$(printf '0x%02x' $(( ($1 >> 8) & 0xff )))"
	w 0x2b "$(printf '0x%02x' $(( $1 & 0xff )))"
	w 0x2b 0x00
	w 0x2b "$2"
	w 0x2c 0x00
	usleep 20000
}
w 0xff 0x85; w 0xa1 0x82
w 0xff 0xac; w 0x00 0x20
w 0xff 0xa6; w 0x2a 0x01
dpcd_write 0x010a 0x01; usleep 10000
dpcd_write 0x0102 0x00; usleep 10000
dpcd_write 0x010a 0x01
usleep 200000
w 0xff 0xac; w 0x00 0x60
w 0xff 0xa6; w 0x2a 0x00
w 0xff 0x81; w 0x07 0xfe; w 0x07 0xff; w 0x0a 0xfc; w 0x0a 0xfe
w 0xff 0x85; w 0x1a "$(printf '0x%02x' $LANE_CNT)"
w 0xff 0xac; w 0x00 0x64; w 0x01 0x0a; w 0x0c 0x85; w 0x0c 0xc5
echo "link training started"
